#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
export CLANG_MODULE_CACHE_PATH="$ROOT/.build/ModuleCache"
export SWIFT_MODULECACHE_PATH="$ROOT/.build/ModuleCache"
OPTIONS=(--configuration release --disable-sandbox --cache-path "$ROOT/.build/cache" --config-path "$ROOT/.build/config" --security-path "$ROOT/.build/security" -Xswiftc -debug-prefix-map -Xswiftc "$ROOT=/Weeklet")
swift build "${OPTIONS[@]}" "$@"
BIN_DIR="$(swift build "${OPTIONS[@]}" "$@" --show-bin-path)"
APP="${WEEKLET_APP_OUTPUT:-$ROOT/build/Weeklet.app}"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN_DIR/Weeklet" "$APP/Contents/MacOS/Weeklet"
cp "$BIN_DIR/WeekletInstaller" "$APP/Contents/MacOS/WeekletInstaller"
cp "$ROOT/Resources/Info.plist" "$APP/Contents/Info.plist"
cp -R "$BIN_DIR/Weeklet_Weeklet.bundle" "$APP/Contents/Resources/"
swift "$ROOT/scripts/make-icon.swift" "$ROOT/build/AppIcon.iconset"
iconutil --convert icns "$ROOT/build/AppIcon.iconset" --output "$APP/Contents/Resources/AppIcon.icns"
strip -S "$APP/Contents/MacOS/Weeklet" "$APP/Contents/MacOS/WeekletInstaller"
codesign --force --options runtime --timestamp=none --identifier com.mgalli97.weeklet.installer --sign "${SIGNING_IDENTITY:--}" "$APP/Contents/MacOS/WeekletInstaller"
codesign --force --options runtime --timestamp=none --sign "${SIGNING_IDENTITY:--}" "$APP"
codesign --verify --strict "$APP"
printf '\nBuilt: %s\n' "$APP"
